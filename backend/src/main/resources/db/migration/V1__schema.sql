-- ASTRA CARDIO schema. Portable between PostgreSQL and H2 (MODE=PostgreSQL).
-- Every reading carries a `source`: NASA (real, OSD-575) or SIMULATED.

CREATE TABLE participant (
    id            VARCHAR(10) PRIMARY KEY,
    sex           VARCHAR(10),
    display_name  VARCHAR(50) NOT NULL
);

CREATE TABLE analysis_run (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at    TIMESTAMP WITH TIME ZONE,
    speed          DOUBLE PRECISION NOT NULL,
    simulate       BOOLEAN NOT NULL,
    status         VARCHAR(20) NOT NULL,
    readings_count INT NOT NULL DEFAULT 0,
    alerts_count   INT NOT NULL DEFAULT 0
);

CREATE TABLE reading (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         BIGINT REFERENCES analysis_run (id),
    participant_id VARCHAR(10) NOT NULL REFERENCES participant (id),
    source         VARCHAR(12) NOT NULL CHECK (source IN ('NASA', 'SIMULATED')),
    kind           VARCHAR(20) NOT NULL CHECK (kind IN ('BIOMARKER_PANEL', 'VITALS')),
    timepoint      VARCHAR(20) NOT NULL,
    mission_phase  VARCHAR(20) NOT NULL,
    day_offset     DOUBLE PRECISION NOT NULL,
    sample_name    VARCHAR(60),
    study          VARCHAR(20),
    hr_bpm         DOUBLE PRECISION,
    hrv_rmssd_ms   DOUBLE PRECISION,
    received_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_reading_participant ON reading (participant_id, kind, id);

CREATE TABLE biomarker_measurement (
    id                             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reading_id                     BIGINT NOT NULL REFERENCES reading (id) ON DELETE CASCADE,
    analyte_key                    VARCHAR(40) NOT NULL,
    nasa_label                     VARCHAR(60) NOT NULL,
    concentration                  DOUBLE PRECISION NOT NULL,
    unit                           VARCHAR(20) NOT NULL,
    percent_of_crew_preflight_mean DOUBLE PRECISION NOT NULL,
    at_assay_upper_limit           BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_measurement_reading ON biomarker_measurement (reading_id);

CREATE TABLE anomaly_result (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reading_id          BIGINT NOT NULL UNIQUE REFERENCES reading (id) ON DELETE CASCADE,
    model               VARCHAR(60) NOT NULL,
    anomaly_score       DOUBLE PRECISION NOT NULL,
    threshold           DOUBLE PRECISION NOT NULL,
    is_atypical         BOOLEAN NOT NULL,
    n_strong_deviations INT NOT NULL DEFAULT 0,
    status              VARCHAR(20) NOT NULL,
    details_json        VARCHAR(8000),
    data_quality_notes  VARCHAR(2000),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE alert (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reading_id      BIGINT NOT NULL REFERENCES reading (id) ON DELETE CASCADE,
    participant_id  VARCHAR(10) NOT NULL REFERENCES participant (id),
    source          VARCHAR(12) NOT NULL,
    stream          VARCHAR(20) NOT NULL,
    status          VARCHAR(20) NOT NULL,
    category        VARCHAR(20) NOT NULL,
    title           VARCHAR(200) NOT NULL,
    message         VARCHAR(2000) NOT NULL,
    anomaly_score   DOUBLE PRECISION NOT NULL,
    timepoint       VARCHAR(20) NOT NULL,
    mission_phase   VARCHAR(20) NOT NULL,
    day_offset      DOUBLE PRECISION NOT NULL,
    guidance_code   VARCHAR(40),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    acknowledged    BOOLEAN NOT NULL DEFAULT FALSE,
    acknowledged_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_alert_created ON alert (id DESC);

CREATE TABLE guidance (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40) NOT NULL UNIQUE,
    title       VARCHAR(200) NOT NULL,
    body        VARCHAR(2000) NOT NULL,
    source_name VARCHAR(200) NOT NULL,
    source_url  VARCHAR(500) NOT NULL
);
