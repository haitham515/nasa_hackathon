-- 24/7 single-astronaut telemetry (SIMULATED stream). Portable PostgreSQL / H2.

CREATE TABLE astronaut (
    id            VARCHAR(20) PRIMARY KEY,
    display_name  VARCHAR(80) NOT NULL,
    role          VARCHAR(80) NOT NULL,
    mission       VARCHAR(80) NOT NULL,
    mission_start TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Typical adult reference ranges, used for illustration only. Edit to change thresholds.
-- Outside [normal_low, normal_high] -> ATTENTION; beyond review_low / review_high -> REVIEW_REQUIRED.
CREATE TABLE telemetry_metric (
    metric_key      VARCHAR(30) PRIMARY KEY,
    label           VARCHAR(60) NOT NULL,
    unit            VARCHAR(20) NOT NULL,
    normal_low      DOUBLE PRECISION,
    normal_high     DOUBLE PRECISION,
    review_low      DOUBLE PRECISION,
    review_high     DOUBLE PRECISION,
    display_min     DOUBLE PRECISION NOT NULL,
    display_max     DOUBLE PRECISION NOT NULL,
    window_seconds  INT NOT NULL,
    sort_order      INT NOT NULL,
    description     VARCHAR(500) NOT NULL
);

CREATE TABLE anomaly_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_key      VARCHAR(30) NOT NULL REFERENCES telemetry_metric (metric_key),
    direction       VARCHAR(10) NOT NULL CHECK (direction IN ('HIGH', 'LOW')),
    worst_status    VARCHAR(20) NOT NULL,
    breached_limit  DOUBLE PRECISION NOT NULL,
    peak_value      DOUBLE PRECISION NOT NULL,
    peak_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_breach_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at        TIMESTAMP WITH TIME ZONE,
    is_open         BOOLEAN NOT NULL,
    normal_streak   INT NOT NULL DEFAULT 0,
    sample_count    INT NOT NULL DEFAULT 0
);
CREATE INDEX idx_event_metric_open ON anomaly_event (metric_key, is_open);

CREATE TABLE telemetry_sample (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_key  VARCHAR(30) NOT NULL REFERENCES telemetry_metric (metric_key),
    metric_value DOUBLE PRECISION NOT NULL,
    recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status      VARCHAR(20) NOT NULL,
    event_id    BIGINT REFERENCES anomaly_event (id) ON DELETE SET NULL,
    source      VARCHAR(12) NOT NULL DEFAULT 'SIMULATED' CHECK (source IN ('SIMULATED'))
);
CREATE INDEX idx_sample_metric_time ON telemetry_sample (metric_key, recorded_at);
CREATE INDEX idx_sample_event ON telemetry_sample (event_id);

CREATE TABLE ai_analysis (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         BIGINT NOT NULL UNIQUE REFERENCES anomaly_event (id) ON DELETE CASCADE,
    severity         VARCHAR(20) NOT NULL,
    provider         VARCHAR(20) NOT NULL,
    model            VARCHAR(60),
    fallback_reason  VARCHAR(500),
    payload_json     VARCHAR(16000) NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);

